// Minimal official CJ Product List V2 requests: conserve free-account points.
// Product identities, paid status, variant stock and destination freight are
// independently checked by the existing verifier after this discovery step.
import { candidateSearches } from './cj-search-strategy.mjs';

const ENDPOINT = 'https://developers.cjdropshipping.com/api2.0/v1/product/listV2';
const CJ_QUOTA = new Set(['1600201']);
const CJ_RATE = new Set(['1600200', '429']);
const CJ_INVALID = new Set(['1600100','400']);
const CJ_AUTH = new Set(['401', '403', '1600002', '1600003']);

export function boundedCJQueries(candidate, now = new Date()) {
  const all = candidateSearches(candidate);
  if (!all.length) return [];
  // Rotate one exact/alternate phrase per day. No 5-query batches consuming
  // 250 CJ points per candidate; current V2 calls cost 50 points each.
  const epochDay = Math.floor(new Date(now).getTime() / 86400000);
  if (!Number.isFinite(epochDay)) throw Error('valid_search_date_required');
  return [all[((epochDay % all.length) + all.length) % all.length]];
}

export function buildCJProductSearchUrl(query, countryCode = 'US') {
  if (typeof query !== 'string' || !query.trim() || query.length > 100)
    throw Error('valid_cj_query_required');
  if (countryCode !== null && countryCode !== 'US') throw Error('unsupported_market');
  const url = new URL(ENDPOINT);
  url.searchParams.set('page','1');
  url.searchParams.set('size','20');
  url.searchParams.set('keyWord',query.trim());
  // Restrictive / optional filters previously masked the cause of CJ failures.
  // Variant inventory and sale status are verified separately; US discovery
  // is only a search hint, not a warehouse or fulfillment guarantee.
  if (countryCode) url.searchParams.set('countryCode',countryCode);
  return url;
}

export function cjSearchDiagnostic(error) {
  // Error messages are generated by our CJ transport; never record messages,
  // tokens, query strings, response bodies or full URLs in public reports.
  const message = String(error?.message || '');
  const match = /\bcode\s+([0-9]{3,9})\b/i.exec(message);
  const code = match?.[1] || (/HTTP\s+(\d{3})\b/.exec(message)?.[1] ?? null);
  if (code === '1600014') return {code,kind:'account_disabled',fatal:true};
  if (code && CJ_QUOTA.has(code)) return {code,kind:'quota_exhausted',fatal:true};
  if (code && CJ_RATE.has(code)) return {code,kind:'rate_limited',fatal:true};
  if (code && CJ_INVALID.has(code)) return {code,kind:'request_rejected',fatal:true};
  if (code && CJ_AUTH.has(code)) return {code,kind:'authentication_rejected',fatal:true};
  if (message.includes('network request failed')) return {code:null,kind:'network_unavailable',fatal:false};
  return {code:code || null,kind:'supplier_api_error',fatal:false};
}
